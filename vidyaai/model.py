def recommend_career(student_parsed_df, student_interests_dict, preprocessor, model, top_n=3):
    """
    Recommends careers based on parsed student scores and interests.

    Args:
        student_parsed_df (pd.DataFrame): DataFrame with 'Subject' and 'Score' columns.
        student_interests_dict (dict): Dictionary of interest areas and preference scores.
        preprocessor: The fitted ColumnTransformer used for feature engineering.
        model: The trained machine learning model (e.g., RandomForestClassifier).
        top_n (int): Number of top career recommendations to return.

    Returns:
        list: A list of tuples, each containing (career, confidence_percentage).
    """

    # 1. Prepare student scores for prediction
    # Ensure all subjects from the training data are present, fill missing with a default (e.g., mean or lowest pass score)
    # Get subject columns from the preprocessor's numerical features
    trained_subjects = [col for col in preprocessor.transformers_[0][1].feature_names_in_ if not col.startswith('Interest_')]
    trained_interests = [col for col in preprocessor.transformers_[0][1].feature_names_in_ if col.startswith('Interest_')]

    student_input_data = {}

    # Fill subject scores
    for subj in trained_subjects:
        score_row = student_parsed_df[student_parsed_df['Subject'].str.contains(subj, case=False, na=False)]
        if not score_row.empty:
            # Assuming score is numerical, if letter grade, convert to a numeric equivalent
            score_val = score_row['Score'].iloc[0]
            if isinstance(score_val, str): # Simple conversion for grades
                if score_val.upper().startswith('A'): score_val = 90
                elif score_val.upper().startswith('B'): score_val = 75
                elif score_val.upper().startswith('C'): score_val = 60
                elif score_val.upper().startswith('D'): score_val = 45
                else: score_val = 40 # Default lowest pass for unknown grades
            student_input_data[subj] = score_val
        else:
            student_input_data[subj] = 60 # Default score if subject is not found (e.g., average)

    # Fill interest scores
    for interest_col in trained_interests:
        interest_name = interest_col.replace('Interest_', '')
        student_input_data[interest_col] = student_interests_dict.get(interest_name, 3) # Default interest score of 3 if not specified

    # Convert to DataFrame for preprocessing
    student_df_for_pred = pd.DataFrame([student_input_data])

    # Reorder columns to match the training data's feature order
    # This is crucial for ColumnTransformer if it relies on column order (it does by default)
    student_df_for_pred = student_df_for_pred[trained_subjects + trained_interests]

    # 2. Preprocess the student's input data
    student_processed_features = preprocessor.transform(student_df_for_pred)

    # 3. Get career probabilities
    probabilities = model.predict_proba(student_processed_features)[0]

    # 4. Map probabilities to career labels
    career_probabilities = list(zip(model.classes_, probabilities))
    career_probabilities.sort(key=lambda x: x[1], reverse=True)

    # 5. Return top N recommendations with confidence
    recommendations = [(career, f"{prob*100:.2f}%") for career, prob in career_probabilities[:top_n]]

    return recommendations

