def extract_text_from_pdf(pdf_path):
    """Extracts text from a PDF file using pdfplumber."""
    text = ''
    try:
        with pdfplumber.open(pdf_path) as pdf:
            for page in pdf.pages:
                text += page.extract_text() + '\n'
    except Exception as e:
        print(f"Error reading PDF with pdfplumber: {e}")
        # Fallback to PyPDF2 if pdfplumber fails
        try:
            with open(pdf_path, 'rb') as file:
                reader = PyPDF2.PdfReader(file)
                for page_num in range(len(reader.pages)):
                    text += reader.pages[page_num].extract_text() + '\n'
        except Exception as e_pypdf2:
            print(f"Error reading PDF with PyPDF2: {e_pypdf2}")
            return None
    return text

def parse_report_card(text):
    """Parses the extracted text to find student name, subjects, and scores."""
    student_name = 'Unknown Student'
    # Regex to find student name (e.g., 'Student Name: [Name]', 'Name: [Name]', 'Student: [Name]')
    name_patterns = [
        r'(?:Student Name|Name|Student)[:\\s]*([A-Za-z]+\\s[A-Za-z]+(?:\\s[A-Za-z]+)?)\\b',
        r'Student\\s+([A-Za-z]+\\s[A-Za-z]+(?:\\s[A-Za-z]+)?)\\b',
        r'Name\\s*:\\s*([A-Za-z]+\\s[A-Za-z]+(?:\\s[A-Za-z]+)?)\\b'
    ]
    for pattern in name_patterns:
        match = re.search(pattern, text, re.IGNORECASE)
        if match:
            student_name = match.group(1).strip()
            break

    # Regex to find subjects and scores/grades
    # This pattern tries to be flexible: Subject Name (score/grade), Subject Name score, Subject Name grade
    # It looks for words (subject name), then numbers (score), or letters (grade).
    subject_score_patterns = [
        r'([A-Za-z\\s]+?)(?:\\s*\\(?[\\s]*([A-DF][+-]?|[0-9]{1,3}(?:\\.[0-9]{1,2})?)[\\s]*\\)?)',
        r'([A-Za-z\\s]+?)\\s*:\\s*([A-DF][+-]?|[0-9]{1,3}(?:\\.[0-9]{1,2})?)'
    ]

    data = {'Subject': [], 'Score': []}
    for line in text.split('\n'):
        line = line.strip()
        if not line:
            continue

        for pattern in subject_score_patterns:
            matches = re.findall(pattern, line)
            for match in matches:
                subject = match[0].strip()
                score = match[1].strip()

                # Simple filtering to avoid capturing non-subject lines
                if len(subject.split()) > 1 and len(score) > 0 and 'total' not in subject.lower() and 'grade' not in subject.lower():
                    # Attempt to convert score to numeric if possible, otherwise keep as string
                    try:
                        score = float(score)
                    except ValueError:
                        pass # Keep as string if it's a letter grade
                    data['Subject'].append(subject)
                    data['Score'].append(score)
                    break # Found a match, move to next line

    df = pd.DataFrame(data)

    # Only apply .str operations if 'Subject' column exists and is not empty
    if not df.empty and pd.api.types.is_string_dtype(df['Subject']):
        # Clean up subject names (remove extra spaces, potential leading/trailing non-alpha chars)
        df['Subject'] = df['Subject'].str.replace(r'[^a-zA-Z\\s]', '', regex=True).str.strip()

    # Remove duplicate subjects (e.g., if extracted multiple times from different formats)
    if not df.empty:
        df = df.drop_duplicates(subset=['Subject'], keep='first')

    return student_name, df


